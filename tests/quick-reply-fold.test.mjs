import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createQuickReplyFold } from '../src/quick-reply-fold.mjs';
const { JSDOM } = createRequire(process.env.JSDOM_DIR || '/tmp/jsd/')('jsdom');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const setup = () => { const dom = new JSDOM('<div id="chat"></div><form id="send_form"><div id="qr--bar"><button type="button" class="qr--button">快捷</button></div><textarea id="send_textarea">输入内容</textarea></form>'); return { dom, doc:dom.window.document }; };
test('点输入框展开，滑动聊天收起，原快捷按钮与输入保持完整', () => {
    const { dom, doc } = setup(), feature = createQuickReplyFold(doc);
    const input = doc.getElementById('send_textarea'), bar = doc.getElementById('qr--bar'), native = bar.firstElementChild;
    const folded = () => doc.documentElement.classList.contains('tvrm-quick-replies-folded');
    let clicks = 0; native.onclick = () => clicks++;
    feature.apply({ enabled:true, open:true }); assert.ok(folded());
    assert.equal(doc.getElementById('tvrm-quick-reply-toggle'), null);
    input.click(); assert.equal(folded(), false);
    native.dispatchEvent(new dom.window.Event('pointerdown', { bubbles:true })); native.click();
    assert.equal(clicks, 1); assert.equal(folded(), false);
    doc.getElementById('chat').dispatchEvent(new dom.window.Event('touchmove', { bubbles:true })); assert.ok(folded());
    input.click(); feature.apply(); assert.equal(folded(), false);
    doc.getElementById('chat').dispatchEvent(new dom.window.Event('wheel', { bubbles:true })); assert.ok(folded());
    input.click(); doc.getElementById('chat').dispatchEvent(new dom.window.Event('pointerdown', { bubbles:true })); assert.ok(folded());
    assert.equal(input.value, '输入内容'); assert.equal(bar.firstElementChild, native);
    feature.destroy(); assert.equal(folded(), false);
    input.click(); assert.equal(folded(), false); dom.window.close();
});
test('快捷栏重建保留临时状态，表单重建与重新启用默认收起', async () => {
    const { dom, doc } = setup(), feature = createQuickReplyFold(doc);
    feature.apply(); doc.getElementById('send_textarea').click();
    const bar = doc.getElementById('qr--bar'); bar.replaceWith(bar.cloneNode(true)); await tick();
    assert.equal(doc.documentElement.classList.contains('tvrm-quick-replies-folded'), false);
    const form = doc.getElementById('send_form'); form.replaceWith(form.cloneNode(true)); await tick();
    assert.ok(doc.documentElement.classList.contains('tvrm-quick-replies-folded'));
    doc.getElementById('send_textarea').click(); assert.equal(doc.documentElement.classList.contains('tvrm-quick-replies-folded'), false);
    feature.apply({ enabled:false }); feature.apply(); assert.ok(doc.documentElement.classList.contains('tvrm-quick-replies-folded'));
    feature.destroy(); dom.window.close();
});
